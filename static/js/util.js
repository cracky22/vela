// Deterministische Avatarfarbe aus dem Namen (Farbton), Helligkeit über CSS-Theme
export function hue(name) {
  let x = 0;
  for (const ch of name || '') x = (x * 31 + ch.charCodeAt(0)) >>> 0;
  return x % 360;
}

export function avatar(name, size = 40) {
  return h('div', { class: 'avatar', style: { '--h': hue(name), width: size + 'px', height: size + 'px', fontSize: Math.round(size * 0.4) + 'px' }, 'aria-hidden': 'true' }, initials(name));
}

export const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

export function throttle(fn, ms) {
  let last = 0, timer = null, lastArgs;
  return (...args) => {
    lastArgs = args;
    const now = Date.now();
    if (now - last >= ms) { last = now; fn(...args); }
    else if (!timer) timer = setTimeout(() => { timer = null; last = Date.now(); fn(...lastArgs); }, ms - (now - last));
  };
}

